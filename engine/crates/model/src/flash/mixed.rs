//! ModelOpt storage metadata over the existing config-derived Flash layer plan.
//! CSF bytes stay opaque: the NVFP4 kernels perform their lossless decoding.
use crate::{
    Result, invalid,
    json::{self, Value, field},
    plan::{Format, ModelPlan},
    safetensors::{self, Dtype, Tensor},
    shapes::*,
};
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
};
/// Extra sidecars in mixed ModelOpt storage exceed the FP8 inventory ceiling.
pub const MAX_MIXED_TENSORS: usize = 500_000;
type Object = BTreeMap<String, Value>;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Storage { Plain, Mxfp8, Fp8Block { block: [u64; 2] }, Nvfp4 { csf: bool, activation_scale: bool } }
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Mixed { pub ignore: Vec<String>, pub layers: BTreeMap<String, Storage> }
fn require(ok: bool, why: &str) -> Result<()> {
    if ok { Ok(()) } else { Err(invalid(why)) }
}
fn block(o: &Object) -> Result<Option<Vec<u64>>> {
    o.get("weight_block_size").map(|v| v.array()?.iter().map(Value::u64).collect()).transpose()
}
// ModelOpt ignore patterns use '*' across module-name components.
fn glob(pattern: &str, text: &str) -> bool {
    let (mut p, mut t, mut star, mut retry) = (0, 0, None, 0);
    let (a, b) = (pattern.as_bytes(), text.as_bytes());
    while t < b.len() {
        if p < a.len() && a[p] != b'*' && a[p] == b[t] { p += 1; t += 1; }
        else if p < a.len() && a[p] == b'*' { star = Some(p); p += 1; retry = t; }
        else if let Some(s) = star { retry += 1; t = retry; p = s + 1; }
        else { return false; }
    }
    while p < a.len() && a[p] == b'*' { p += 1; }
    p == a.len()
}
impl Mixed {
    pub(crate) fn exclusions(q: &Object) -> Result<Vec<String>> {
        require(q.contains_key("ignore") || q.contains_key("exclude_modules"), "missing mixed exclusion list")?;
        let mut ignore = Vec::new();
        for key in ["ignore", "exclude_modules"] {
            if let Some(v) = q.get(key) {
                for p in v.array()? { ignore.push(p.string()?.to_owned()); }
            }
        }
        Ok(ignore)
    }
    pub fn parse(q: &Object) -> Result<Self> {
        require(field(q, "quant_method")?.string()? == "modelopt"
            && field(q, "quant_algo")?.string()? == "MIXED_PRECISION"
            && q.get("kv_cache_quant_algo").is_none_or(|v| v == &Value::Null), "unsupported ModelOpt precision/cache")?;
        let ignore = Self::exclusions(q)?;
        let mut layers = BTreeMap::new();
        for (name, v) in field(q, "quantized_layers")?.object()? {
            let o = v.object()?;
            let algo = field(o, "quant_algo")?.string()?;
            let csf = o.get("weight_scale_encoding").map(Value::string).transpose()?;
            require(csf.is_none() || csf == Some("csf") && algo == "NVFP4", "unsupported block scale encoding")?;
            let group = o.get("group_size").map(Value::u64).transpose()?;
            let block = block(o)?;
            let storage = match algo {
                "MXFP8" => {
                    require(group.is_some() || block.is_some(), "missing MXFP8 group or block size")?;
                    require(group.is_none_or(|v| v == 32) && block.as_deref().is_none_or(|v| v == [1, 32]),
                        "invalid MXFP8 group or block size")?;
                    Storage::Mxfp8
                }
                "FP8_PB_WO" => {
                    require(block.as_deref() == Some(&[FP8_BLOCK, FP8_BLOCK]) && group.is_none_or(|v| v == FP8_BLOCK),
                        "invalid FP8 block size")?;
                    Storage::Fp8Block { block: [FP8_BLOCK, FP8_BLOCK] }
                }
                "NVFP4" | "W4A16_NVFP4" => {
                    require(group == Some(16) && block.is_none(), "invalid NVFP4 group or block size")?;
                    Storage::Nvfp4 { csf: csf.is_some(), activation_scale: algo == "NVFP4" }
                }
                _ => return Err(invalid(format!("unsupported quant_algo {algo}"))),
            };
            require(!name.is_empty(), "invalid quantization target")?;
            layers.insert(name.clone(), storage);
        }
        require(!layers.is_empty(), "empty mixed quantization map")?;
        Ok(Self { ignore, layers })
    }
    pub fn storage(&self, module: &str) -> Storage {
        if self.excluded(module) { return Storage::Plain; }
        self.layers.iter().filter(|(p, _)| module == p.as_str()
            || module.strip_prefix(p.as_str()).is_some_and(|s| s.starts_with('.')))
            .max_by_key(|(p, _)| p.len()).map_or(Storage::Plain, |(_, &s)| s)
    }
    pub(crate) fn excluded(&self, module: &str) -> bool {
        self.ignore.iter().any(|p| glob(p, module))
    }
}

/// Transform logical weights generated by the existing layer planner. The normal
/// reconciliation then checks every expected dtype/shape and rejects extra text tensors.
pub(crate) fn inventory(q: &Mixed, entries: &mut BTreeMap<String, TensorEntry>, headers: &BTreeMap<String, Tensor>) -> Result<()> {
    let logical = std::mem::take(entries);
    for (_, mut e) in logical {
        let name = e.name.clone();
        let module = name.strip_suffix(".weight").unwrap_or(&name);
        let lexical = matches!(e.role.part, Part::Lexical { .. });
        // The lexical table's one global multiplier is shared by all shards.
        if let Some(p) = name.strip_suffix(".ngram_embedding.weight_scale") {
            if matches!(q.storage(&format!("{p}.ngram_embedding")), Storage::Nvfp4 { csf: false, .. }) {
                e.name.push_str("_2"); e.dtype = Dtype::F32; e.role.store = Store::Scalar;
                entries.insert(e.name.clone(), e); continue;
            }
        }
        let storage = if name.ends_with(".weight") { q.storage(module) } else { Storage::Plain };
        let mut add = |suffix: &str, dtype, shape, store| {
            let name = format!("{module}.{suffix}");
            entries.insert(name.clone(), TensorEntry { name, dtype, shape, role: Role { store, ..e.role } });
        };
        match storage {
            Storage::Plain => {
                // Preserve original norm bytes; no conversion to the old BF16 assumption.
                if (name.ends_with(".hc_norm.weight") || name.contains(".ple.norm_"))
                    && headers.get(&name).is_some_and(|t| matches!(t.dtype, Dtype::Bf16 | Dtype::F32)) {
                    e.dtype = headers[&name].dtype;
                }
            }
            Storage::Mxfp8 | Storage::Fp8Block { .. } | Storage::Nvfp4 { .. } => {
                require(e.shape.len() == 2, "quantized target is not a matrix")?;
                let (rows, cols) = (e.shape[0], e.shape[1]);
                match storage {
                    Storage::Mxfp8 => {
                        require(cols % 32 == 0, "MXFP8 K must divide into 32-value groups")?;
                        e.dtype = Dtype::F8E4M3;
                        add("weight_scale", Dtype::U8, vec![rows, cols / 32], Store::BlockScale);
                    }
                    Storage::Fp8Block { block: [br, bc] } => {
                        require(br == FP8_BLOCK && bc == FP8_BLOCK && cols % bc == 0,
                            "FP8 block K must divide into the configured blocks")?;
                        // KFp8Block128 in public vLLM commit
                        // 355553ac22dca4080929ea8f88a446f15df1f3ba, file
                        // vllm/model_executor/layers/quantization/modelopt.py,
                        // stores F32 scales in either layout.
                        // Keep the header layout. This plan does not reshape scale bytes.
                        let scale = format!("{module}.weight_scale");
                        let t = headers.get(&scale).ok_or_else(|| invalid(format!("missing tensor {scale}")))?;
                        let (r, c) = (rows.div_ceil(br), cols / bc);
                        require(t.dtype == Dtype::F32 && (t.shape == [r, c] || t.shape == [r, 1, c, 1]),
                            "invalid FP8 weight_scale dtype or block grid")?;
                        e.dtype = Dtype::F8E4M3;
                        add("weight_scale", Dtype::F32, t.shape.clone(), Store::BlockScale);
                    }
                    Storage::Nvfp4 { csf, activation_scale } => {
                        require(cols % 16 == 0, "NVFP4 K must divide into 16-value groups")?;
                        e.dtype = Dtype::U8; e.shape[1] /= 2;
                        if csf {
                            for (suffix, dtype, rank) in [("nvfp4_csf_fixed", Dtype::U8, 2), ("nvfp4_csf_exceptions", Dtype::U32, 1)] {
                                let n = format!("{module}.weight_scale.{suffix}");
                                let t = headers.get(&n).ok_or_else(|| invalid(format!("missing CSF tensor {n}")))?;
                                require(t.dtype == dtype && t.shape.len() == rank
                                    && t.shape.iter().product::<u64>() <= rows * cols / 16
                                    && (rank == 1 || t.shape.iter().all(|&n| n > 0)),
                                    "invalid opaque CSF descriptor")?;
                                add(&format!("weight_scale.{suffix}"), dtype, t.shape.clone(), Store::BlockScale);
                            }
                        } else { add("weight_scale", Dtype::F8E4M3, vec![rows, cols / 16], Store::BlockScale); }
                        if !lexical {
                            add("weight_scale_2", Dtype::F32, vec![], Store::Scalar);
                            if activation_scale { add("input_scale", Dtype::F32, vec![], Store::Scalar); }
                        }
                    }
                    Storage::Plain => unreachable!(),
                }
            }
        }
        entries.insert(e.name.clone(), e);
    }
    Ok(())
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Class { RoutedNvfp4, MtpNvfp4, AttentionMxfp8, SharedMxfp8, PleNvfp4, Bf16, Fp32, Constants, Vision, BlockFp8 }
#[derive(Debug, Default)]
pub struct Total { pub tensors: usize, pub bytes: u64 }
pub struct Plan { pub model: ModelPlan, pub files: BTreeMap<String, String>, pub classes: BTreeMap<Class, Total> }
impl Plan {
    /// A metadata-only loader: never opens payload files or allocates weight buffers.
    pub fn open(config: &Path, tensor_map: &Path, world: u64) -> Result<Self> {
        require(world == 1, "mixed Flash storage currently requires world 1")?;
        let model = ModelPlan::from_config(&safetensors::read_bounded(config, CONFIG_BYTES)?)
            .map_err(|e| invalid(e.to_string()))?;
        require(
            matches!(model.format, Format::Mixed(_)),
            "expected mixed ModelOpt checkpoint",
        )?;
        let bytes = safetensors::read_bounded(tensor_map, 128 << 20)?;
        let doc = json::parse(
            &bytes,
            json::Limits {
                bytes: 128 << 20,
                nodes: MAX_MIXED_TENSORS * 10,
                ..Default::default()
            },
        )?;
        require(
            doc.object()?.len() <= MAX_MIXED_TENSORS,
            "tensor map limit exceeded",
        )?;
        let (mut files, mut headers) = (BTreeMap::new(), BTreeMap::new());
        for (name, v) in doc.object()? {
            let o = v.object()?;
            let file = field(o, "file")?.string()?;
            safetensors::validate_mixed_shard_name(file)?;
            let dtype = Dtype::parse(field(o, "dtype")?.string()?)?;
            let shape = field(o, "shape")?.array()?.iter().map(Value::u64).collect::<Result<Vec<_>>>()?;
            require(shape.len() <= MAX_TENSOR_RANK, "tensor rank limit exceeded")?;
            let end = shape.iter().try_fold(dtype.bytes(), |n, &d| n.checked_mul(d).ok_or_else(|| invalid("tensor bytes overflow")))?;
            headers.insert(name.clone(), Tensor { dtype, shape, start: 0, end });
            files.insert(name.clone(), file.to_owned());
        }
        let root = config.parent().filter(|p| !p.as_os_str().is_empty()).unwrap_or(Path::new("."));
        for file in files.values().collect::<BTreeSet<_>>() {
            safetensors::validate_model_path(root, file)?;
        }
        let model = model.with_headers(&headers).map_err(|e| invalid(e.to_string()))?;
        Self::from_model(model, files)
    }
    pub fn from_model(model: ModelPlan, files: BTreeMap<String, String>) -> Result<Self> {
        require(matches!(model.format, Format::Mixed(_)) && !model.shape.tensors.is_empty()
            && files.len() == model.shape.tensors.len(), "expected reconciled mixed model and file map")?;
        for file in files.values().collect::<BTreeSet<_>>() { safetensors::validate_mixed_shard_name(file)?; }
        let mut classes = BTreeMap::<Class, Total>::new();
        let mut aggregate = 0u64;
        for t in &model.shape.tensors {
            require(files.contains_key(&t.name), "missing tensor file mapping")?;
            let bytes = t.shape.iter().try_fold(t.dtype.bytes(), |n, &d| n.checked_mul(d).ok_or_else(|| invalid("tensor bytes overflow")))?;
            aggregate = aggregate.checked_add(bytes).ok_or_else(|| invalid("checkpoint bytes overflow"))?;
            let class = Self::class(&model, t)?;
            let total = classes.entry(class).or_default();
            total.tensors += 1;
            total.bytes = total.bytes.checked_add(bytes)
                .ok_or_else(|| invalid("class bytes overflow"))?;
        }
        Ok(Self { model, files, classes })
    }
    fn class(model: &ModelPlan, t: &TensorEntry) -> Result<Class> {
        if t.role.place == Place::Unused { return Ok(Class::Vision); }
        let Format::Mixed(q) = &model.format else { return Err(invalid("expected mixed storage plan")); };
        let module = t.name.split_once(".weight").map_or(t.name.as_str(), |(p, _)| p);
        if matches!(q.storage(module), Storage::Fp8Block { .. }) { return Ok(Class::BlockFp8); }
        if matches!(t.role.part, Part::Lexical { .. }) || t.name.contains(".ngram_embedding.") { return Ok(Class::PleNvfp4); }
        if matches!(t.role.part, Part::Expert { .. }) {
            return Ok(if matches!(t.role.place, Place::Draft { .. }) { Class::MtpNvfp4 } else { Class::RoutedNvfp4 });
        }
        if q.storage(module) == Storage::Mxfp8 {
            return Ok(if matches!(t.role.part, Part::Shared(_)) { Class::SharedMxfp8 } else { Class::AttentionMxfp8 });
        }
        Ok(match t.dtype { Dtype::Bf16 => Class::Bf16, Dtype::F32 => Class::Fp32, _ => Class::Constants })
    }
    /// Existing Flash cache: FP32 K/V plus FP32 index vectors, including optional MTP.
    pub fn cache_bytes(&self, tokens: u64, mtp: bool) -> Result<(u64, u64)> {
        require(tokens <= self.model.shape.max_positions, "context exceeds config")?;
        let (mut per_token, mut recurrent) = (0, 0);
        for l in self.model.shape.layers.iter().chain(self.model.shape.draft.iter().filter(|_| mtp)) {
            match l.mixer {
                Mixer::Attention(a) => per_token += (2 * a.kv_heads * a.head_dim
                    + a.index.map_or(0, |i| i.kv_heads * i.dim)) * 4,
                Mixer::Linear(a) => recurrent += (a.value_heads * a.value_dim * a.key_dim
                    + (2 * a.key_heads * a.key_dim + a.value_heads * a.value_dim) * (a.conv - 1)) * 4
                    + super::gdn_chunk_tail_bytes(a.value_heads, a.key_heads, a.key_dim, a.value_dim),
            }
        }
        Ok((per_token.checked_mul(tokens).ok_or_else(|| invalid("KV bytes overflow"))?, recurrent))
    }
    pub fn resident_bytes(&self, ple: bool, mtp: bool) -> u64 {
        self.model.shape.tensors.iter().filter(|t| t.role.place != Place::Unused
            && (mtp || !matches!(t.role.place, Place::Draft { .. }))
            && (ple || !t.name.contains(".ngram_embedding.")))
            .map(|t| t.shape.iter().product::<u64>() * t.dtype.bytes()).sum()
    }
    /// Borrowed typed handoff; no expanded scales or changed multiplication order.
    pub fn nvfp4(&self, module: &str) -> Result<Nvfp4<'_>> {
        let Format::Mixed(q) = &self.model.format else { return Err(invalid("expected mixed storage")); };
        let Storage::Nvfp4 { csf, activation_scale } = q.storage(module) else { return Err(invalid("expected NVFP4 module")); };
        let find = |suffix: &str| self.model.shape.tensors.binary_search_by(|t| t.name.as_str().cmp(&format!("{module}.{suffix}")))
            .map(|i| &self.model.shape.tensors[i]).map_err(|_| invalid(format!("missing {module}.{suffix}")));
        let weight = find("weight")?;
        let lexical = matches!(weight.role.part, Part::Lexical { .. });
        let scales = if csf { ScaleView::Csf { fixed: find("weight_scale.nvfp4_csf_fixed")?, exceptions: find("weight_scale.nvfp4_csf_exceptions")? } }
            else { ScaleView::E4m3(find("weight_scale")?) };
        let global = if lexical {
            let prefix = module.rsplit_once(".shard_").ok_or_else(|| invalid("missing PLE shard"))?.0;
            self.model.shape.tensors.iter().find(|t| t.name == format!("{prefix}.weight_scale_2")).ok_or_else(|| invalid("missing PLE global scale"))?
        } else { find("weight_scale_2")? };
        Ok(Nvfp4 { weight, scales, global, input: if activation_scale && !lexical { Some(find("input_scale")?) } else { None },
            rows: weight.shape[0], columns: weight.shape[1] * 2 })
    }
    /// Future bounded disk row request: packed values, block scales and the shared global scale.
    pub fn ple_row(&self, shard: u32, row: u64) -> Result<PleRow<'_>> {
        let weight = self.model.shape.tensors.iter().find(|t| t.role.part == (Part::Lexical { part: shard }) && t.role.store == Store::Weight)
            .ok_or_else(|| invalid("unknown PLE shard"))?;
        let matrix = self.nvfp4(weight.name.strip_suffix(".weight").ok_or_else(|| invalid("invalid PLE weight"))?)?;
        require(row < matrix.rows, "PLE row out of bounds")?;
        Ok(PleRow { packed_offset: row * matrix.columns / 2, scale_offset: row * matrix.columns / 16,
            packed_bytes: matrix.columns / 2, scale_bytes: matrix.columns / 16, matrix })
    }
}
pub enum ScaleView<'a> { E4m3(&'a TensorEntry), Csf { fixed: &'a TensorEntry, exceptions: &'a TensorEntry } }
pub struct Nvfp4<'a> { pub weight: &'a TensorEntry, pub scales: ScaleView<'a>, pub global: &'a TensorEntry,
    pub input: Option<&'a TensorEntry>, pub rows: u64, pub columns: u64 }
pub struct PleRow<'a> { pub matrix: Nvfp4<'a>, pub packed_offset: u64, pub scale_offset: u64,
    pub packed_bytes: u64, pub scale_bytes: u64 }

#[cfg(test)]
mod tests {
    use super::*;

    fn parse(text: &str) -> Result<Mixed> {
        Mixed::parse(json::parse(text.as_bytes(), json::Limits::default())?.object()?)
    }
    const CONFIG: &str = r#"{"quant_method":"modelopt","quant_algo":"MIXED_PRECISION",
        "ignore":["model.keep*"],"exclude_modules":["model.skip*"],"quantized_layers":{
        "model":{"quant_algo":"MXFP8","weight_block_size":[1,32]},
        "model.block":{"quant_algo":"FP8_PB_WO","weight_block_size":[128,128]}}}"#;

    #[test]
    fn public_mixed_schema_combines_exclusions_and_reads_blocks() {
        let q = parse(CONFIG).unwrap();
        for name in ["model.keep.q", "model.skip.q"] { assert_eq!(q.storage(name), Storage::Plain); }
        assert_eq!(q.storage("model.q"), Storage::Mxfp8);
        assert_eq!(q.storage("model.block.q"), Storage::Fp8Block { block: [128, 128] });
        assert_eq!(q.storage("models"), Storage::Plain);
        let only_public = CONFIG.replace("\"ignore\":[\"model.keep*\"],", "");
        assert_eq!(parse(&only_public).unwrap().storage("model.skip.q"), Storage::Plain);
        let both = CONFIG.replace("\"weight_block_size\":[1,32]", "\"group_size\":32,\"weight_block_size\":[1,32]");
        assert_eq!(parse(&both).unwrap().storage("model.q"), Storage::Mxfp8);
    }

    #[test]
    fn mixed_schema_rejects_conflicts_and_unknown_codec() {
        for text in [
            CONFIG.replace("\"weight_block_size\":[1,32]", "\"group_size\":16,\"weight_block_size\":[1,32]"),
            CONFIG.replace("[1,32]", "[2,32]"), CONFIG.replace("[1,32]", "[1,16]"),
            CONFIG.replace("[128,128]", "[64,128]"), CONFIG.replace("[128,128]", "[128]"),
            CONFIG.replace("\"exclude_modules\":[\"model.skip*\"]", "\"exclude_modules\":null"),
            CONFIG.replace("\"ignore\":", "\"kv_cache_quant_algo\":\"FP8\",\"ignore\":"),
            CONFIG.replace("\"quant_algo\":\"MXFP8\",\"weight_block_size\":[1,32]",
                "\"quant_algo\":\"NVFP4\",\"group_size\":16,\"weight_scale_encoding\":\"csf_32x2_v1\""),
        ] { assert!(parse(&text).is_err(), "{text}"); }
    }

    fn logical(rows: u64, cols: u64) -> BTreeMap<String, TensorEntry> {
        let name = "model.block.weight".to_owned();
        BTreeMap::from([(name.clone(), TensorEntry { name, dtype: Dtype::Bf16, shape: vec![rows, cols],
            role: Role { place: Place::Layer(0), part: Part::Shared(Proj::Gate), store: Store::Weight } })])
    }
    fn header(dtype: Dtype, shape: Vec<u64>) -> BTreeMap<String, Tensor> {
        BTreeMap::from([("model.block.weight_scale".into(), Tensor { dtype, shape, start: 0, end: 0 })])
    }

    #[test]
    fn fp8_block_headers_preserve_scale_layout_and_shared_role() {
        let q = parse(CONFIG).unwrap();
        // KFp8Block128 permits a partial output block and a full input block.
        for shape in [vec![2, 2], vec![2, 1, 2, 1]] {
            let mut entries = logical(129, 256);
            inventory(&q, &mut entries, &header(Dtype::F32, shape.clone())).unwrap();
            let weight = &entries["model.block.weight"];
            let scale = &entries["model.block.weight_scale"];
            assert_eq!((weight.dtype, &weight.shape), (Dtype::F8E4M3, &vec![129, 256]));
            assert_eq!((scale.dtype, &scale.shape, scale.role.store), (Dtype::F32, &shape, Store::BlockScale));
            assert_eq!(scale.role.part, Part::Shared(Proj::Gate));
            assert!(!entries.contains_key("model.block.weight_scale_inv"));
        }
    }

    #[test]
    fn fp8_block_headers_reject_bad_grid_dtype_and_input_width() {
        let q = parse(CONFIG).unwrap();
        for h in [header(Dtype::Bf16, vec![2, 2]), header(Dtype::F32, vec![1, 2]),
            header(Dtype::F32, vec![2, 2, 1, 1]), header(Dtype::F32, vec![2, 1, 2]), BTreeMap::new()] {
            assert!(inventory(&q, &mut logical(129, 256), &h).is_err());
        }
        assert!(inventory(&q, &mut logical(129, 255), &header(Dtype::F32, vec![2, 2])).is_err());
    }
}

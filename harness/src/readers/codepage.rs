//! Single-byte code pages for `\'hh` bytes in RTF: Windows-1250 (Central
//! European), Windows-1251 (Cyrillic) and Mac Roman, besides Windows-1252
//! in the text reader, and the code page of each RTF font charset. The tables
//! come from the iconv mappings; a byte that a code page leaves undefined
//! maps to the C1 control of the same value, as in
//! [`super::text::windows_1252`].

/// The character for byte `b` in code page `page`, or `None` when this
/// build has no table for `page`.
pub(super) fn decode(page: u32, b: u8) -> Option<char> {
    let high: &[u16; 128] = match page {
        1252 | 28591 => return Some(super::text::windows_1252(b)),
        1250 => &CP1250,
        1251 => &CP1251,
        10000 => &MAC_ROMAN,
        _ if b < 0x80 => return Some(b as char),
        _ => return None,
    };
    Some(if b < 0x80 { b as char } else { char::from_u32(high[(b - 0x80) as usize] as u32).unwrap_or('\u{fffd}') })
}

/// The code page of an RTF font charset (`\fcharsetN`), or `None` for the
/// default charset (1) and unknown values, which use the document code page.
/// The symbol charset (2) reads as Windows-1252.
pub(super) fn for_charset(charset: i64) -> Option<u32> {
    Some(match charset {
        0 | 2 => 1252,
        77 => 10000,
        128 => 932,
        129 => 949,
        134 => 936,
        136 => 950,
        161 => 1253,
        162 => 1254,
        163 => 1258,
        177 => 1255,
        178 => 1256,
        186 => 1257,
        204 => 1251,
        222 => 874,
        238 => 1250,
        255 => 437,
        _ => return None,
    })
}

